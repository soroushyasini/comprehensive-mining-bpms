const sessions = new Map();
let checks = 0;

async function call(action, payload = {}, options = {}) {
    const actor = options.actor || 'admin';
    const session = sessions.get(actor) || {};
    const data = new FormData();
    data.append('action',action);
    data.append('payload',JSON.stringify(payload));
    if (options.file) data.append('file',new Blob([options.file],{type:'application/pdf'}),'fixture.pdf');
    const headers = {'X-Contract-Fixture-Actor':actor};
    if (session.cookie) headers.Cookie=session.cookie;
    if (session.token && !options.noCsrf) headers['X-CSRF-Token']=session.token;
    const response = await fetch(url,{method:'POST',body:data,headers});
    const cookie = response.headers.get('set-cookie');
    if (cookie) session.cookie=cookie.split(';')[0];
    sessions.set(actor,session);
    const raw = response.headers.get('content-type')?.includes('application/json') ? await response.json() : Buffer.from(await response.arrayBuffer());
    assert.equal(response.status,options.status || 200, action + ': ' + (Buffer.isBuffer(raw)?'binary':JSON.stringify(raw)));
    checks++;
    if (raw.csrf_token) session.token=raw.csrf_token;
    return raw.data ?? raw;
}
